function updateDutchCalc(){
  var visitors = parseInt(document.getElementById('rngVisitors').value, 10);
  var aov = parseInt(document.getElementById('rngAov').value, 10);
  var speed = parseFloat(document.getElementById('rngSpeed').value);

  document.getElementById('lblVisitors').textContent = visitors.toLocaleString('nl-NL') + ' bezoekers';
  document.getElementById('lblAov').textContent = '€' + aov;

  var speedText = speed.toFixed(1) + ' seconden';
  if(speed <= 2.0) speedText += ' (Snel)';
  else if(speed <= 3.5) speedText += ' (Gemiddeld)';
  else speedText += ' (Traag)';
  document.getElementById('lblSpeed').textContent = speedText;

  // Conversion loss estimation: baseline ideal is 1.5s; every second delay causes ~7% conversion loss
  var delaySeconds = Math.max(0, speed - 1.5);
  var baseConversionRate = 0.022; // 2.2% baseline
  var expectedOrders = visitors * baseConversionRate;
  var lossFraction = 1 - Math.pow(0.93, delaySeconds);
  var monthlyLoss = Math.round(expectedOrders * aov * lossFraction);
  var yearlyLoss = monthlyLoss * 12;

  document.getElementById('calcLossVal').textContent = '€' + monthlyLoss.toLocaleString('nl-NL') + ' / maand';
  document.getElementById('calcYearlyNote').innerHTML = 'Dat is ruim <b>€' + yearlyLoss.toLocaleString('nl-NL') + ' per jaar</b> dat je misloopt aan bezoekers die wegklikken.';
}
